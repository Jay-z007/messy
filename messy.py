PASSING_MARK = 40


def assign_grade(score):
    """Return a letter grade for a numeric mark."""
    if score >= 90:
        return "A"
    elif score >= 75:
        return "B"
    elif score >= PASSING_MARK:
        return "C"
    else:
        return "F"


def calculate_average(marks):
    """Return average marks using the original (count - 1) divisor."""
    total = 0
    count = 0
    for mark in marks:
        total = total + mark
        count = count + 1
    return total / (count - 1)


def count_above_average(marks):
    """Return how many scores are above the class average."""
    class_average = calculate_average(marks)
    above_average_count = 0
    for mark in marks:
        if mark > class_average:
            above_average_count = above_average_count + 1
    return above_average_count


STUDENTS = ["Aman", "Riya", "Karan", "Neha"]
MARKS = [78, 32, 91, 45]


def process_class(students, marks):
    """Return class totals and per-student grade rows."""
    average = calculate_average(marks)
    above_average_count = count_above_average(marks)
    total_marks = 0
    for mark in marks:
        total_marks = total_marks + mark

    rows = []
    for index in range(len(students)):
        grade = assign_grade(marks[index])
        if marks[index] > 100:
            rows.append(
                {
                    "name": students[index],
                    "marks": marks[index],
                    "grade": grade,
                    "result": "Invalid",
                    "message": f"{students[index]} Invalid marks",
                }
            )
        else:
            if marks[index] >= PASSING_MARK:
                result = "Pass"
                message = f"{students[index]} has passed"
            else:
                result = "Fail"
                message = f"{students[index]} has failed"
            rows.append(
                {
                    "name": students[index],
                    "marks": marks[index],
                    "grade": grade,
                    "result": result,
                    "message": message,
                }
            )

    return {
        "average": average,
        "above_average_count": above_average_count,
        "rows": rows,
        "total_students": len(students),
        "students_found": len(students) > 0,
        "total_marks": total_marks,
    }


def print_report(report):
    """Print the class report to the console."""
    print(f"Average marks: {report['average']}")
    print(f"Students above average: {report['above_average_count']}")

    for row in report["rows"]:
        if row["result"] == "Invalid":
            print(row["message"])
        else:
            print(f"Name: {row['name']}")
            print(f"Marks: {row['marks']}")
            print(f"Grade: {row['grade']}")
            print(f"Result: {row['result']}")
            print(row["message"])

    print(f"Total students: {report['total_students']}")

    if report["students_found"]:
        print("Students found")

    if report["total_students"] == 0:
        print("No students found")
    else:
        print("Processing completed")

    print(f"Total marks: {report['total_marks']}")


if __name__ == "__main__":
    print_report(process_class(STUDENTS, MARKS))
